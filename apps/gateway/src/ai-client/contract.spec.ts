import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Contract test: the generated TypeScript types must describe the committed OpenAPI document.
 * (CI also regenerates both and fails on any diff; this catches it locally and in `make test`.)
 */
const ROOT = join(__dirname, '..', '..', '..', '..');
const spec = JSON.parse(
  readFileSync(join(ROOT, 'packages', 'contracts', 'openapi', 'ai-service.json'), 'utf8'),
) as {
  paths: Record<string, Record<string, { requestBody?: unknown; security?: unknown }>>;
  components: {
    schemas: Record<string, { properties?: Record<string, unknown>; required?: string[] }>;
  };
};
const generated = readFileSync(join(__dirname, 'generated', 'ai-service.ts'), 'utf8');

describe('AI service contract', () => {
  it('the generated types declare every schema of the OpenAPI document', () => {
    const names = Object.keys(spec.components.schemas);
    expect(names.length).toBeGreaterThan(8);
    for (const name of names) {
      expect(generated).toMatch(new RegExp(`^    ${name}:`, 'm'));
    }
  });

  it('declares POST /v1/process', () => {
    expect(spec.paths['/v1/process']).toHaveProperty('post');
    expect(generated).toContain("'/v1/process'");
    expect(generated).toContain('process_v1_process_post');
  });

  it('has the schemas the gateway client relies on', () => {
    for (const name of [
      'ProcessRequest',
      'ProcessResponse',
      'Reply',
      'ReplyButton',
      'Meta',
      'UserContext',
      'InputPayload',
      'ActiveMedication',
    ]) {
      expect(spec.components.schemas).toHaveProperty(name);
    }
  });

  it('request fields the client sends exist in the contract (a rename would break the build)', () => {
    const request = spec.components.schemas['ProcessRequest']?.properties ?? {};
    expect(Object.keys(request).sort()).toEqual([
      'context',
      'input',
      'options',
      'request_id',
      'user',
    ]);
    const reply = spec.components.schemas['Reply']?.properties ?? {};
    expect(Object.keys(reply).sort()).toEqual(['buttons', 'language', 'text']);
  });

  it('is marked auto-generated so nobody edits it by hand', () => {
    expect(generated).toContain('auto-generated by openapi-typescript');
  });

  it('contains no environment-specific values', () => {
    const text = JSON.stringify(spec);
    expect(text).not.toContain('contract-export-token');
    expect(text).not.toContain('localhost:5432');
  });
});
